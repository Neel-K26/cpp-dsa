// pattern of 11,22,333 double or number count pattern using for loop and ascending pyramid
using namespace std;
#include<iostream>
main()
{
    int i,j;
    for (i=1;i<=5;i++)
    {
        cout<<"\n";
        for (j=1;j<=i;j++)
            cout<<""<<i;
    }
}
