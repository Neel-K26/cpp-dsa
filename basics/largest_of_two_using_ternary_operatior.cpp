// wrting program to find greatest of two using ternary operator
using namespace std;
#include  <iostream>
int main()
{
    int num1,num2,largest;
    cout<<"\n Enter the Number : ";
    cin>>num1>>num2;
    largest=num1>num2?num1:num2;
    // often read as num1 is greater than num 2 ? if yes print num 1 if not : print num 2
    cout<<"\n The largest number is :"<<largest;
    return 0;


}
