// largest number between 2 using if_else demonstration
using namespace std;
#include<iostream>;
main()
{
    int a,b,large;
    cout<<"\n Enter the both numbers :";
    cin>>a>>b;
    if (a>b)
        large=a;
    else
        large=b;
    cout<<"\n Large number is " << large;

}
