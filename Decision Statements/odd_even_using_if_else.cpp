// Odd and Even Numbers using If_else demonstration
using namespace std;
#include<iostream>
main()
{
    int num;
    cout<<"\n Enter the Number :";
    cin>>num;
    if (num%2==0)
        cout<<"\n The Number is Even "<< num;
    else
        cout<<"\n The Number is Odd ";
    return 0;

}
